def __getattr__(name: str) -> Any:
    if name in {"SsmdAnalysis", "SsmdAnalysisIssue", "SsmdAnalysisReport"}:
        from .analysis import models

        return getattr(models, name)
    if name == "ProjectedText":
        from .analysis.projection import ProjectedText

        return ProjectedText
    if name == "CachedAnalysis":
        from .analysis.cache import CachedAnalysis

        return CachedAnalysis
    if name == "SpeechFreezeFailure":
        from .speech.failures import SpeechFreezeFailure

        return SpeechFreezeFailure
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


